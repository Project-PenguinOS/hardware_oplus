package com.oplus.view.material;

/* Stub: ColorOS RenderNode corner material. Only carried to OplusMaterialUtil. */
public class OplusMaterialCornerParams {
    private float mRadius;
    private float mWeight;

    public OplusMaterialCornerParams(float radius, float weight) {
        mRadius = radius;
        mWeight = weight;
    }

    public float getRadius() {
        return mRadius;
    }

    public void setRadius(float radius) {
        mRadius = radius;
    }

    public float getWeight() {
        return mWeight;
    }

    public void setWeight(float weight) {
        mWeight = weight;
    }
}
